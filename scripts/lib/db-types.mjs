// DBTYPES.1 — turn supabase/schema/snapshot.json into the Database type the
// supabase-js client understands. Pure, so the mapping can be tested.

const SCALARS = new Map([
  ['text', 'string'], ['uuid', 'string'], ['date', 'string'], ['inet', 'string'], ['tsvector', 'string'],
  ['citext', 'string'], ['name', 'string'], ['interval', 'string'],
  ['timestamp with time zone', 'string'], ['timestamp without time zone', 'string'],
  ['time with time zone', 'string'], ['time without time zone', 'string'],
  ['integer', 'number'], ['smallint', 'number'], ['bigint', 'number'], ['numeric', 'number'],
  ['real', 'number'], ['double precision', 'number'],
  ['boolean', 'boolean'], ['json', 'Json'], ['jsonb', 'Json'],
])

/** A Postgres type as printed by format_type, as a TypeScript type. */
export function tsType(pgType, relations = {}) {
  const t = String(pgType).trim()
  if (t.endsWith('[]')) {
    const inner = tsType(t.slice(0, -2), relations)
    return /[ |]/.test(inner) ? `(${inner})[]` : `${inner}[]`
  }
  const base = t.replace(/\(.*\)$/, '').replace(/^public\./, '').trim()
  if (SCALARS.has(base)) return SCALARS.get(base)
  if (base === 'character' || base === 'character varying') return 'string'
  if (base === 'void') return 'undefined'
  if (relations[base]) return `Row<${JSON.stringify(base)}>`
  return 'unknown'
}

/** Split on commas outside parentheses. */
export function splitTop(text) {
  const out = []
  let depth = 0
  let cur = ''
  for (const ch of String(text)) {
    if (ch === '(') depth++
    if (ch === ')') depth--
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = '' } else cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

/** 'p_a uuid, VARIADIC p_b text[]' → [['p_a','uuid'],['p_b','text[]']]; unnamed arguments are dropped. */
export function parseArgs(text) {
  return splitTop(text).flatMap((raw) => {
    const m = /^(?:(?:IN|INOUT|VARIADIC)\s+)?("?[a-z_][a-z0-9_]*"?)\s+(.+)$/i.exec(raw)
    return m && !/^OUT\s/i.test(raw) ? [[m[1].replaceAll('"', ''), m[2]]] : []
  })
}

function returnsType(result, relations) {
  const r = String(result).trim()
  const table = /^TABLE\((.*)\)$/s.exec(r)
  if (table) return `{ ${parseArgs(table[1]).map(([n, t]) => `${JSON.stringify(n)}: ${tsType(t, relations)} | null`).join('; ')} }[]`
  const setof = /^SETOF\s+(.+)$/i.exec(r)
  if (setof) { const x = tsType(setof[1], relations); return /[ |]/.test(x) ? `(${x})[]` : `${x}[]` }
  return tsType(r, relations)
}

const key = (k) => JSON.stringify(k)

export function renderDatabaseTypes(snapshot) {
  const { relations, functions, enums, foreign_keys: fks } = snapshot
  const fkByTable = new Map()
  for (const [table, cols, ref, refCols] of fks) {
    if (table.includes('.') || ref.includes('.') || !relations[ref]) continue
    if (!fkByTable.has(table)) fkByTable.set(table, [])
    fkByTable.get(table).push({ cols, ref, refCols })
  }
  const relationships = (t) => `[${(fkByTable.get(t) || []).map((f) => `{ foreignKeyName: ${key(`${t}_${f.cols.join('_')}_fkey`)}; columns: ${JSON.stringify(f.cols)}; isOneToOne: false; referencedRelation: ${key(f.ref)}; referencedColumns: ${JSON.stringify(f.refCols)} }`).join(', ')}]`
  const row = (r) => r.columns.map(([c, t, nullable]) => `${key(c)}: ${tsType(t, {})}${nullable ? ' | null' : ''}`).join('; ')
  const insert = (r) => r.columns.map(([c, t, nullable, hasDefault]) => `${key(c)}${nullable || hasDefault ? '?' : ''}: ${tsType(t, {})}${nullable ? ' | null' : ''}`).join('; ')
  const update = (r) => r.columns.map(([c, t, nullable]) => `${key(c)}?: ${tsType(t, {})}${nullable ? ' | null' : ''}`).join('; ')
  const names = Object.keys(relations).sort()
  const tables = names.filter((n) => relations[n].kind === 'table')
    .map((n) => `      ${key(n)}: { Row: { ${row(relations[n])} }; Insert: { ${insert(relations[n])} }; Update: { ${update(relations[n])} }; Relationships: ${relationships(n)} }`)
  const views = names.filter((n) => relations[n].kind !== 'table')
    .map((n) => `      ${key(n)}: { Row: { ${row(relations[n])} }; Relationships: ${relationships(n)} }`)
  const byName = new Map()
  for (const [name, args, result] of functions) {
    if (/^(trigger|event_trigger)$/.test(String(result).trim())) continue
    // The catalog's identity arguments do not say which have defaults, so all are optional.
    const a = parseArgs(args).map(([n, t]) => `${key(n)}?: ${tsType(t, relations)}`).join('; ')
    if (!byName.has(name)) byName.set(name, [])
    byName.get(name).push(`{ Args: { ${a} }; Returns: ${returnsType(result, relations)} }`)
  }
  const fns = [...byName.keys()].sort().map((n) => `      ${key(n)}: ${byName.get(n).join(' | ')}`)
  const enumLines = Object.keys(enums).sort().map((n) => `      ${key(n)}: ${enums[n].map(key).join(' | ')}`)
  return `// GENERATED by scripts/generate-db-types.mjs from supabase/schema/snapshot.json. Do not edit.
// Through migration ${snapshot.through_migration}. Refresh: npm run db:types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]
type Row<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row']

export type Database = {
  public: {
    Tables: {
${tables.join('\n')}
    }
    Views: {
${views.join('\n')}
    }
    Functions: {
${fns.join('\n')}
    }
    Enums: {
${enumLines.join('\n')}
    }
    CompositeTypes: {}
  }
}
`
}
